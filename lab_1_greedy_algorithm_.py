# Define the observed rewards for each machine
rewards_task1 = {
    'A': [3, 2, 4],
    'B': [6, 7],
    'C': [5, 4, 6]
}

# Calculate Q(a) for each machine using the arithmetic mean
q_values_task1 = {}
for machine, r_list in rewards_task1.items():
    q_values_task1[machine] = sum(r_list) / len(r_list)

# Display the estimated Q(a) for every machine
for machine, r_list in rewards_task1.items():
    print(f"Machine {machine}")
    print(f"Rewards: {r_list}")
    print(f"Q({machine}) = {q_values_task1[machine]:.2f}")

# Select the machine with the highest Q(a)
greedy_selected_machine_task1 = max(q_values_task1, key=q_values_task1.get)

# Display the selected machine
print(f"\nGreedy Selected Machine: {greedy_selected_machine_task1}")

# Define the observed rewards for each machine (same as before)
rewards = {
    'A': [3, 2, 4],
    'B': [6, 7],
    'C': [5, 4, 6]
}

# Task 1 - Initialize
# Initially: Q(A)=Q(B)=Q(C)=0 and N(A)=N(B)=N(C)=0
current_q_values = {machine: 0.0 for machine in rewards.keys()}
play_counts = {machine: 0 for machine in rewards.keys()}

print("Initial Q values:", current_q_values)
print("Initial Play counts:", play_counts)
print("\n--- Processing Rewards Incrementally ---")

# Task 2 - Update After Every Play
# Process rewards for each machine sequentially to update Q(a) incrementally
# Note: This processes all rewards for a given machine before moving to the next.
# In a real MAB scenario, plays would be interleaved and chosen by the algorithm.
# For this problem, we're calculating the final Q values as if all these rewards
# were observed from playing each specific machine.

for machine, r_list in rewards.items():
    print(f"\nProcessing Machine {machine} rewards:")
    for reward in r_list:
        # 3. Increment N(a)
        play_counts[machine] += 1
        # 4. Update Q(a) using the incremental formula
        q_old = current_q_values[machine]
        n_a = play_counts[machine]
        q_new = q_old + (reward - q_old) / n_a
        current_q_values[machine] = q_new
        print(f"  Reward: {reward}, N({machine}): {n_a}, Q_old({machine}): {q_old:.2f}, Q_new({machine}): {q_new:.2f}")

# Task 3: Python Implementation - Display results
print("\n--- Final Estimated Q(a) Values ---")
for machine in rewards.keys():
    print(f"Machine {machine}")
    print(f"Rewards: {rewards[machine]}")
    print(f"Q({machine}) = {current_q_values[machine]:.2f}")

# Identify the machine having the highest current Q(a)
greedy_selected_machine_incremental = max(current_q_values, key=current_q_values.get)

# Display the selected machine
print(f"\nGreedy Selected Machine (Incremental Update): {greedy_selected_machine_incremental}")